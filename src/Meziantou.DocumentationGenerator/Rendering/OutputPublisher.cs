using Meziantou.Framework;

namespace Meziantou.DocumentationGenerator.Rendering;

/// <summary>
/// Publishes a validated staging directory to the output directory.
/// <list type="bullet">
/// <item><description>A new or empty output directory is replaced by the staging directory with a single rename.</description></item>
/// <item><description>Otherwise each file is moved into place (a rename on the same volume), stale files listed in the previous manifest are deleted, and the new manifest is written last.</description></item>
/// <item><description>Files that the generator does not own are never deleted or overwritten; a conflict fails before anything is changed.</description></item>
/// <item><description>A journal lists the files being published, so an interrupted publication is completed by the next build.</description></item>
/// </list>
/// </summary>
internal static class OutputPublisher
{
    public const string JournalFileName = ".docgen-publish.json";

    public static void Publish(OutputStaging staging, FullPath output, OutputManifest manifest)
    {
        var files = staging.Files;
        manifest.Files = [.. files];
        var manifestContent = manifest.Serialize();

        if (!Directory.Exists(output) || !Directory.EnumerateFileSystemEntries(output).Any())
        {
            if (Directory.Exists(output))
            {
                Directory.Delete(output);
            }

            File.WriteAllText(staging.Root / OutputManifest.FileName, manifestContent);
            Directory.Move(staging.Root, output);
            return;
        }

        var previous = OutputManifest.TryRead(output / OutputManifest.FileName);
        var journal = OutputManifest.TryRead(output / JournalFileName);
        var owned = new HashSet<string>(previous?.Files ?? [], StringComparer.OrdinalIgnoreCase);
        owned.UnionWith(journal?.Files ?? []);

        var conflicts = files
            .Where(f => !owned.Contains(f) && (File.Exists(output / f) || Directory.Exists(output / f)))
            .Concat(files.Where(f => HasFileAncestor(output, f)))
            .Distinct(StringComparer.Ordinal)
            .Order(StringComparer.Ordinal)
            .ToList();
        if (conflicts.Count > 0)
            throw new PublicationException($"The output directory contains files that were not generated by this tool and would be overwritten: {string.Join(", ", conflicts.Take(10))}. Move them or choose another output directory");

        WriteAtomically(output / JournalFileName, new OutputManifest { Generator = manifest.Generator, Files = [.. owned.Union(files, StringComparer.OrdinalIgnoreCase).Order(StringComparer.Ordinal)] }.Serialize());

        foreach (var file in files)
        {
            var destination = output / file;
            destination.CreateParentDirectory();
            if (Directory.Exists(destination))
            {
                Directory.Delete(destination, recursive: true);
            }

            File.Move(staging.Root / file, destination, overwrite: true);
        }

        var current = new HashSet<string>(files, StringComparer.OrdinalIgnoreCase);
        foreach (var stale in owned.Where(f => !current.Contains(f)).Order(StringComparer.Ordinal))
        {
            var path = output / stale;
            if (!path.IsChildOf(output))
                continue;

            if (File.Exists(path))
            {
                File.Delete(path);
            }

            DeleteEmptyParents(path.Parent, output);
        }

        WriteAtomically(output / OutputManifest.FileName, manifestContent);
        File.Delete(output / JournalFileName);
    }

    private static bool HasFileAncestor(FullPath output, string relativePath)
    {
        for (var parent = (output / relativePath).Parent; parent != output && parent.IsChildOf(output); parent = parent.Parent)
        {
            if (File.Exists(parent))
                return true;
        }

        return false;
    }

    private static void DeleteEmptyParents(FullPath directory, FullPath root)
    {
        while (directory != root && directory.IsChildOf(root) && Directory.Exists(directory) && !Directory.EnumerateFileSystemEntries(directory).Any())
        {
            Directory.Delete(directory);
            directory = directory.Parent;
        }
    }

    private static void WriteAtomically(FullPath path, string content)
    {
        var temporary = path.Parent / (path.Name + ".tmp");
        File.WriteAllText(temporary, content);
        File.Move(temporary, path, overwrite: true);
    }
}
